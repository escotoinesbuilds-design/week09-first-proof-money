"use client";

import { useState } from "react";

type Props = {
  studentCount: number;
  verifiedStartCount: number;
  flaggedCount: number;
};

type ExplanationResponse = {
  summary?: string;
  source?: string;
  error?: string;
};

export default function AiSummary({
  studentCount,
  verifiedStartCount,
  flaggedCount,
}: Props) {
  const [summary, setSummary] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  async function requestExplanation() {
    setLoading(true);
    setError(null);
    try {
      const response = await fetch("/api/ai-explanation", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ placementId: "FP-1004" }),
      });
      const result: ExplanationResponse = await response.json();
      if (!response.ok) {
        setError(result.error ?? "The LLM explanation could not be generated.");
        return;
      }
      if (result.source !== "llm" || typeof result.summary !== "string") {
        setError("The LLM service returned an invalid explanation.");
        return;
      }
      setSummary(result.summary);
    } catch {
      setError("The LLM explanation request failed. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <section className="panel ai-panel">
      <div className="ai-heading">
        <span className="ai-sparkle" aria-hidden="true">
          ✦
        </span>
        <div>
          <p className="eyebrow">
            {summary ? "LIVE LLM · EXPLANATION ONLY" : "SIMULATED SAMPLE"}
          </p>
          <h2>{summary ? "LLM Explanation" : "Simulated AI Summary"}</h2>
        </div>
      </div>
      {summary ? (
        <p className="ai-copy">{summary}</p>
      ) : (
        <>
          <p className="ai-copy">
            This fictional sample has {studentCount} placements.{" "}
            {verifiedStartCount} show a verified paid start and are eligible for
            human payment review. {flaggedCount} placements have warning flags
            that require staff review.
          </p>
          <p className="ai-simulated-label">
            SIMULATED SUMMARY — sample copy, not generated by an LLM.
          </p>
        </>
      )}
      <button
        className="ai-button"
        disabled={loading}
        onClick={requestExplanation}
        type="button"
      >
        {loading ? "Generating explanation…" : "Explain a flagged placement"}
      </button>
      {error && (
        <p className="ai-error" role="alert">
          {error}
        </p>
      )}
      <p className="ai-boundary">
        An LLM may explain fictional structured data and the deterministic
        verification result only. It cannot verify evidence, decide
        employability, change eligibility, or authorize payment.
      </p>
    </section>
  );
}
